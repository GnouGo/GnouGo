// Controlled provider, real GnOuGoAgentWebHost and real Blazor interaction. No paid inference or workflow execution.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium, request } = await import(process.env.PLAYWRIGHT_MODULE_PATH);
const [url, token, output] = process.argv.slice(2);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const anonymous = await request.newContext();
  assert.equal((await anonymous.get(`${url}/api/planning`)).status(), 200);
  async function start(name, mode) {
    await page.goto(`${url}/planning`);
    await page.waitForFunction(() => window.Blazor?._internal?.navigationManager != null);
    await page.waitForTimeout(300);
    if (mode === 'default') assert.equal(await page.locator('#plan-thresholds').inputValue(), 'diagnostic');
    else if (mode) await page.locator('#plan-thresholds').selectOption(mode);
    else assert.equal(await page.locator('#plan-thresholds').count(), 0);
    await page.locator('#plan-name').fill(name);
    const marker = name.startsWith('cancelled') ? ' cancelled test' : name.startsWith('correction') ? ' correction fixture' : name.startsWith('empty') ? ' empty fixture' : name.startsWith('partial') ? ' partial fixture' : '';
    await page.locator('#plan-prompt').fill('Return the required public numeric result named result with value 42.' + marker);
    await page.getByRole('button', { name: 'Create plan', exact: true }).click();
    await page.waitForURL(/\/planning\/[a-f0-9]+$/);
    return new URL(page.url()).pathname.split('/').at(-1);
  }
  const ordinarySessionId = await start('ordinary-browser', null);
  await page.getByText('Planning stopped', { exact: true }).waitFor({ timeout: 20000 });
  assert.ok(!(await page.locator('body').innerText()).includes('Protected planning access requires'));
  await page.getByText('Debug workflow generation', { exact: true }).waitFor();
  assert.equal((await anonymous.get(`${url}/api/planning/${ordinarySessionId}`)).status(), 200);
  for (const suffix of ['inspection', 'calls/content?key=foreign', 'calls/export?key=foreign'])
    assert.equal((await anonymous.get(`${url}/api/planning/${ordinarySessionId}/${suffix}`)).status(), 403);
  const anonymousAntiforgery = await (await anonymous.get(`${url}/api/planning/antiforgery`)).json();
  assert.equal((await anonymous.post(`${url}/api/planning`, { headers: { [anonymousAntiforgery.headerName]: anonymousAntiforgery.requestToken },
    data: { name: 'unauthorized-diagnostic', prompt: 'Return 42', thresholdMode: 'diagnostic' } })).status(), 403);
  await anonymous.dispose();
  await page.goto(`${url}/local-operator#${token}`);
  await page.waitForURL(`${url}/planning`);
  await page.locator('#plan-name').waitFor();
  await page.goto(`${url}/`);
  await page.getByLabel('Threshold policy').waitFor();
  assert.equal(await page.getByLabel('Threshold policy').inputValue(), 'diagnostic');
  await page.getByLabel('Threshold policy').selectOption('strict');
  assert.equal(await page.getByLabel('Threshold policy').inputValue(), 'strict');
  const defaults = await (await page.request.get(`${url}/api/llm/providers`)).json();
  assert.equal(defaults.find(provider => provider.isDefault).defaultModel, 'gpt-6.1-sol-2026-09-29');
  assert.equal(defaults.find(provider => provider.isDefault).defaultModelSource, 'keyvault_provider_configuration');
  const sessionId = await start('diagnostic-browser', 'default');
  await page.getByRole('heading', { name: 'Generation timeline', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.planning-timeline .phase-active'));
  await page.screenshot({ path: `${output}/active-phase.png` });
  await page.reload();
  await page.getByRole('heading', { name: 'Generation timeline', exact: true }).waitFor();
  await page.getByText('Ready for your review', { exact: true }).waitFor({ timeout: 90000 });
  await page.getByRole('heading', { name: 'Advisory thresholds exceeded', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Traces', exact: true }).click();
  const tracePanel = page.locator('.gnougo-trace-panel--open');
  await tracePanel.getByRole('heading', { name: 'Planning traces', exact: true }).waitFor();
  await tracePanel.getByRole('button', { name: 'Inspect request / response', exact: true }).first().click();
  await tracePanel.getByRole('heading', { name: /Request and response schema/ }).waitFor();
  await tracePanel.getByRole('heading', { name: /Response and tool calls/ }).waitFor();
  assert.ok(!(await tracePanel.innerText()).includes('CONTROLLED_PROVIDER_KEY'));
  await page.screenshot({ path: `${output}/otel-input-output.png` });
  await tracePanel.getByRole('button', { name: 'Close trace panel', exact: true }).click();
  await page.getByRole('heading', { name: 'Advisory thresholds exceeded', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/warning-continues.png` });
  const inspect = page.getByRole('button', { name: 'Inspect LLM exchange', exact: true });
  await inspect.first().click();
  await page.getByRole('heading', { name: /Actual serialized HTTP request/ }).waitFor();
  assert.equal(await page.getByText('CONTROLLED_PROVIDER_KEY', { exact: false }).count(), 0);
  const exported = await page.request.get(new URL(await page.locator('a[download]').filter({ hasText: 'Export complete redacted JSON' }).first().getAttribute('href'), url).href);
  assert.equal(exported.status(), 200, await exported.text());
  const full = await exported.text();
  assert.ok(!full.includes('CONTROLLED_PROVIDER_KEY'));
  const detail = JSON.parse(full);
  assert.equal(detail.http.transport.Attempts.length, 2);
  assert.deepEqual(detail.http.transport.Attempts.map(attempt => attempt.Status), [500, 200]);
  assert.ok(detail.http.transport.RequestBody.includes('max_completion_tokens'));
  assert.ok(full.includes('reasoning_tokens'));
  await writeFile(`${output}/call-redacted.json`, full);
  await page.getByRole('heading', { name: /Actual serialized HTTP request/ }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/llm-exchange.png` });
  const calls = (await (await page.request.get(`${url}/api/planning/${sessionId}/inspection`)).json()).calls;
  assert.equal(calls.length, 5);
  assert.equal((await page.request.get(`${url}/api/planning/${sessionId}/calls/export?key=${encodeURIComponent('foreign:foreign:1:hash')}`)).status(), 404);
  assert.equal((await page.request.get(`${url}/api/planning/${sessionId}/inspection`, { headers: { Origin: 'https://foreign.invalid' } })).status(), 403);
  assert.equal((await page.request.post(`${url}/api/planning/foreign/stop`)).status(), 400);
  const antiforgery = await (await page.request.get(`${url}/api/planning/antiforgery`)).json();
  assert.equal((await page.request.post(`${url}/api/planning/foreign/stop`, { headers: { [antiforgery.headerName]: antiforgery.requestToken } })).status(), 404);
  const contentUrl = `${url}/api/planning/${sessionId}/calls/content?key=${encodeURIComponent(calls[0].key)}`;
  let reconstructed = '', offset = 0;
  while (true) {
    const part = await (await page.request.get(`${contentUrl}&offset=${offset}&count=8192&search=reasoning_tokens`)).json();
    assert.equal(part.offset, offset); reconstructed += part.text;
    if (part.complete) { assert.equal(reconstructed.length, part.totalCharacters); break; }
    assert.ok(part.nextOffset > offset); offset = part.nextOffset;
  }
  assert.deepEqual(JSON.parse(reconstructed), detail);
  const search = await (await page.request.get(`${contentUrl}&search=reasoning_tokens`)).json();
  assert.ok(search.nextMatch >= 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Responsive planning view must fit the viewport');
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  const correctedSessionId = await start('correction-browser', 'diagnostic');
  await page.getByText('Ready for your review', { exact: true }).waitFor({ timeout: 90000 });
  await page.screenshot({ path: `${output}/correction-loop.png` });
  const emptySessionId = await start('empty-browser', 'diagnostic');
  await page.getByText('Planning stopped', { exact: true }).waitFor({ timeout: 20000 });
  const partialSessionId = await start('partial-browser', 'diagnostic');
  await page.getByText('Planning stopped', { exact: true }).waitFor({ timeout: 20000 });
  await page.reload();
  await page.getByText('Planning stopped', { exact: true }).waitFor();
  await page.waitForFunction(() => window.Blazor?._internal?.navigationManager != null);
  await page.waitForTimeout(300);
  await page.getByRole('button', { name: 'Inspect LLM exchange', exact: true }).first().click();
  await page.getByRole('heading', { name: /HTTP response, including invalid or partial content/ }).waitFor();
  const partialCalls = (await (await page.request.get(`${url}/api/planning/${partialSessionId}/inspection`)).json()).calls;
  const partialExport = await (await page.request.get(`${url}/api/planning/${partialSessionId}/calls/export?key=${encodeURIComponent(partialCalls[0].key)}`)).json();
  assert.equal(partialExport.http.transport.Attempts.length, 1);
  assert.equal(partialExport.http.transport.Attempts[0].ObservedStatus, 200);
  assert.equal(partialExport.http.transport.Attempts[0].Status, null);
  assert.ok(partialExport.http.transport.Attempts[0].PartialBody.length > 0);
  assert.equal(partialExport.http.transport.Attempts[0].ResponseBodyComplete, false);
  const strictSessionId = await start('strict-browser', 'strict');
  await page.getByText('Planning stopped', { exact: true }).waitFor({ timeout: 20000 });
  const cancelledSessionId = await start('cancelled-browser', 'diagnostic');
  await page.getByRole('heading', { name: 'Generation timeline', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.planning-timeline .phase-active'));
  await page.getByRole('button', { name: 'Cancel planning', exact: true }).click();
  await page.getByText('Cancelled', { exact: true }).first().waitFor({ timeout: 30000 });
  await page.reload();
  await page.getByText('Cancelled', { exact: true }).first().waitFor();
  const omitted = await page.request.post(`${url}/api/planning`, { headers: { [antiforgery.headerName]: antiforgery.requestToken },
    data: { name: 'cancelled-api-default', prompt: 'Return 42 cancelled test' } });
  assert.equal(omitted.status(), 200, await omitted.text());
  const apiDefault = await omitted.json(); assert.equal(apiDefault.thresholdMode, 'diagnostic');
  assert.equal((await page.request.post(`${url}/api/planning/${apiDefault.id}/stop`, { headers: { [antiforgery.headerName]: antiforgery.requestToken } })).status(), 200);
  await writeFile(`${output}/result.json`, JSON.stringify({ provider: 'controlled HTTP fixture; no paid inference', ordinarySessionId, sessionId, strictSessionId, correctedSessionId, emptySessionId, partialSessionId, cancelledSessionId, browserErrors: errors }, null, 2));
  assert.deepEqual(errors, []);
} catch (error) { await page.screenshot({ path: `${output}/failure.png`, fullPage: true }); await writeFile(`${output}/failure.txt`, await page.locator("body").innerText() + "\n" + JSON.stringify(errors)); throw error; } finally { await browser.close(); }
