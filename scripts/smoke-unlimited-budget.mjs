// Controlled HTTP provider, actual Agent.Server and protected Blazor settings. No paid inference.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium, request } = await import(process.env.PLAYWRIGHT_MODULE_PATH);
const [url, token, output] = process.argv.slice(2);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
const page = await context.newPage();
try {
  const anonymous = await request.newContext();
  assert.equal((await anonymous.get(`${url}/api/application-llm-budget`)).status(), 403);
  assert.equal((await anonymous.post(`${url}/api/application-llm-budget`, { data: { mode: 'limited' } })).status(), 403);
  // Same handoff destination as the embedded Desktop launcher; no open redirect is accepted.
  const desktopToken = 'a'.repeat(32);
  await page.goto(`${url}/local-operator?desktopToken=${desktopToken}#${token}`);
  await page.waitForURL(`${url}/?desktopToken=${desktopToken}`);
  assert.ok(!page.url().includes(token));
  const initial = await (await page.request.get(`${url}/api/application-llm-budget`)).json();
  assert.equal(initial.policy.mode, 'unlimited');
  assert.equal((await page.request.post(`${url}/api/application-llm-budget`, { data: { mode: 'limited' } })).status(), 400);
  assert.equal((await page.request.get(`${url}/api/application-llm-budget`, { headers: { Origin: 'https://foreign.invalid' } })).status(), 403);
  async function selectBudget(mode) {
    await page.goto(`${url}/settings/llm-budget`);
    await page.locator('#llm-budget-settings[data-interactive="true"]').waitFor();
    await page.locator('#application-budget-mode').selectOption(mode);
    await page.locator('#save-application-budget').click();
    await page.getByText('Saved for new plans and executions.', { exact: true }).waitFor();
    assert.equal((await (await page.request.get(`${url}/api/application-llm-budget`)).json()).policy.mode, mode);
  }
  await selectBudget('limited');
  await page.goto(`${url}/planning`);
  await page.locator('#planningReview[data-interactive="true"]').waitFor();
  assert.equal(await page.locator('#plan-thresholds').inputValue(), 'diagnostic');
  await page.locator('#plan-name').fill('budget-browser');
  await page.locator('#plan-prompt').fill('Return the required public numeric result named result with value 42.');
  await page.getByRole('button', { name: 'Create plan', exact: true }).click();
  await page.waitForURL(/\/planning\/[a-f0-9]+$/);
  const limitedSessionId = page.url().split('/').at(-1);
  await page.getByText('Planning stopped', { exact: true }).waitFor({ timeout: 20000 });
  await page.getByText('LLM_BUDGET_EXCEEDED', { exact: true }).first().waitFor();
  await page.locator('#start-with-current-settings').waitFor();
  assert.ok((await page.locator('body').innerText()).includes('not_started'));
  await page.screenshot({ path: `${output}/limited-before-dispatch.png` });
  const limited = await (await page.request.get(`${url}/api/planning/${limitedSessionId}`)).json();
  assert.equal(limited.calls, 0); assert.equal(limited.canStartWithCurrentSettings, true);
  assert.equal(limited.diagnostics[0].budgetFailure.allowance, 50);
  await selectBudget('unlimited');
  await page.goto(`${url}/planning/${limitedSessionId}`);
  await page.locator('#planningReview[data-interactive="true"]').waitFor();
  await page.locator('#start-with-current-settings').click();
  await page.waitForURL(address => address.pathname.startsWith('/planning/') && !address.pathname.endsWith(limitedSessionId));
  const unlimitedSessionId = page.url().split('/').at(-1);
  await page.waitForFunction(() => document.querySelector('.planning-timeline .phase-active'));
  await page.screenshot({ path: `${output}/unlimited-active.png` });
  await page.reload();
  await page.getByText('Ready for your review', { exact: true }).waitFor({ timeout: 90000 });
  assert.ok((await page.locator('body').innerText()).includes('Unlimited — usage and costs tracked'));
  await page.getByRole('heading', { name: 'Advisory thresholds exceeded', exact: true }).waitFor();
  await page.screenshot({ path: `${output}/unlimited-warning-continues.png` });
  const completed = await (await page.request.get(`${url}/api/planning/${unlimitedSessionId}`)).json();
  assert.equal(completed.effectivePolicy.applicationBudget.mode, 'unlimited');
  assert.equal(completed.effectivePolicy.budget, null);
  assert.equal(completed.costEstimateAvailable, true);
  assert.ok(completed.estimatedCost > 0);
  const csrf = await (await page.request.get(`${url}/api/planning/antiforgery`)).json();
  const headers = { [csrf.headerName]: csrf.requestToken };
  assert.equal((await page.request.post(`${url}/api/planning/${unlimitedSessionId}/start-with-current-settings`, { headers })).status(), 409);
  assert.equal((await page.request.post(`${url}/api/planning/foreign/start-with-current-settings`, { headers })).status(), 404);
  assert.equal((await anonymous.post(`${url}/api/planning/${limitedSessionId}/start-with-current-settings`, { headers })).status(), 403);
  const preserved = await (await page.request.get(`${url}/api/planning/${limitedSessionId}`)).json();
  assert.equal(preserved.calls, 0); assert.equal(preserved.effectivePolicy.applicationBudget.mode, 'limited');
  assert.equal(preserved.status, limited.status);
  const call = page.getByRole('button', { name: 'Inspect LLM exchange', exact: true }).first();
  await call.click(); await page.getByRole('heading', { name: /Actual serialized HTTP request/ }).waitFor();
  assert.ok(!(await page.locator('body').innerText()).includes('CONTROLLED_BUDGET_SECRET'));
  await page.screenshot({ path: `${output}/unlimited-llm-exchange.png` });
  await writeFile(`${output}/result.json`, JSON.stringify({ provider: 'controlled HTTP', desktopPath: 'single-use bootstrap with embedded return destination; native window not automated', limitedSessionId, unlimitedSessionId }, null, 2));
  await anonymous.dispose();
} finally { await browser.close(); }
