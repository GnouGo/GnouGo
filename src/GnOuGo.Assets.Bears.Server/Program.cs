static bool TryReadInt(
    IQueryCollection query,
    string name,
    int defaultValue,
    out int value,
    out string? error)
{
    value = defaultValue;
    if (!query.TryGetValue(name, out var rawValue))
    {
        error = null;
        return true;
    }

    if (int.TryParse(rawValue.ToString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out value))
    {
        error = null;
        return true;
    }

    error = $"{name} must be an integer.";
    return false;
}

static bool TryReadDouble(
    IQueryCollection query,
    string name,
    double defaultValue,
    out double value,
    out string? error)
{
    value = defaultValue;
    if (!query.TryGetValue(name, out var rawValue))
    {
        error = null;
        return true;
    }

    if (double.TryParse(rawValue.ToString(), NumberStyles.Float, CultureInfo.InvariantCulture, out value))
    {
        error = null;
        return true;
    }

    error = $"{name} must be a number.";
    return false;
}

static bool TryReadNullableDouble(
    IQueryCollection query,
    string name,
    out double? value,
    out string? error)
{
    value = null;
    if (!query.TryGetValue(name, out var rawValue) || string.IsNullOrWhiteSpace(rawValue.ToString()))
    {
        error = null;
        return true;
    }

    if (double.TryParse(rawValue.ToString(), NumberStyles.Float, CultureInfo.InvariantCulture, out var parsedValue))
    {
        value = parsedValue;
        error = null;
        return true;
    }

    error = $"{name} must be a number.";
    return false;
}

static bool TryReadBool(
    IQueryCollection query,
    string name,
    bool defaultValue,
    out bool value,
    out string? error)
{
    value = defaultValue;
    if (!query.TryGetValue(name, out var rawValue))
    {
        error = null;
        return true;
    }

    if (bool.TryParse(rawValue.ToString(), out value))
    {
        error = null;
        return true;
    }

    error = $"{name} must be true or false.";
    return false;
}

static bool TryReadEnum<T>(
    IQueryCollection query,
    string name,
    T defaultValue,
    out T value,
    out string? error)
    where T : struct, Enum
{
    value = defaultValue;
    if (!query.TryGetValue(name, out var rawValue))
    {
        error = null;
        return true;
    }

    if (Enum.TryParse(rawValue.ToString(), ignoreCase: true, out value) && Enum.IsDefined(value))
    {
        error = null;
        return true;
    }

    error = $"Unknown {name}. Supported values: {string.Join(", ", Enum.GetNames<T>())}.";
    return false;
}

static bool TryGetAnimation(HttpContext context, out GnouGnouBearAnimation animation)
{
    var value = context.Request.Query["animation"].ToString();
    if (string.IsNullOrWhiteSpace(value))
    {
        animation = GnouGnouBearAnimation.None;
        return true;
    }

    return Enum.TryParse(value, ignoreCase: true, out animation)
        && Enum.IsDefined(animation);
}

static GalleryAppearance? TryGetAppearance(HttpContext context, GnouGnouBearOptions baseOptions)
{
    var token = context.Request.Query["appearance"].ToString();
    if (string.IsNullOrWhiteSpace(token))
        return null;

    return CreateGalleryAppearances(baseOptions).FirstOrDefault(appearance =>
        string.Equals(appearance.Token, token, StringComparison.OrdinalIgnoreCase));
}

