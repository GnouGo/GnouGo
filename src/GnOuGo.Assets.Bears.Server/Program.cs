using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using GnOuGo.Assets.Bears;

var builder = WebApplication.CreateSlimBuilder(args);

var app = builder.Build();

app.MapMethods("/", ["GET"], (RequestDelegate)(async context =>
{
    var options = CreateRandomBearOptions(TryGetSeed(context));
    var html = RenderAnimationGallery(options);

    context.Response.Headers.CacheControl = "no-store";
    context.Response.ContentType = "text/html; charset=utf-8";
    await context.Response.WriteAsync(html);
}));

app.MapMethods("/bear.svg", ["GET"], (RequestDelegate)(async context =>
{
    if (!TryGetAnimation(context, out var animation))
    {
        context.Response.StatusCode = StatusCodes.Status400BadRequest;
        context.Response.ContentType = "text/plain; charset=utf-8";
        await context.Response.WriteAsync(
            $"Unknown animation. Supported values: {string.Join(", ", Enum.GetNames<GnouGnouBearAnimation>())}.");
        return;
    }

    var baseOptions = CreateRandomBearOptions(TryGetSeed(context));
    var appearance = TryGetAppearance(context, baseOptions);
    var options = (appearance?.Options ?? baseOptions) with
    {
        Animation = animation,
        Size = 512,
        SvgIdPrefix = "standalone-preview",
        Title = $"{animation} GnOuGo animation",
        Description = $"Standalone {animation} animation generated by GnOuGo.Assets.Bears."
    };
    var svg = GnouGnouBearSvgGenerator.Generate(options);

    context.Response.Headers.CacheControl = "no-store";
    context.Response.ContentType = "image/svg+xml; charset=utf-8";
    await context.Response.WriteAsync(svg);
}));

app.MapMethods("/text", ["GET"], (RequestDelegate)(async context =>
{
    var initialOptions = new GnouGnouTextOptions();
    if (TryCreateTextOptions(context, out var requestedOptions, out _)
        && TryGenerateTextSvg(requestedOptions, out _, out _))
    {
        initialOptions = requestedOptions;
    }

    context.Response.Headers.CacheControl = "no-store";
    context.Response.ContentType = "text/html; charset=utf-8";
    await context.Response.WriteAsync(TextDemoPage.Render(initialOptions));
}));

app.MapMethods("/text.svg", ["GET"], (RequestDelegate)(async context =>
{
    if (!TryCreateTextOptions(context, out var options, out var parseError))
    {
        context.Response.StatusCode = StatusCodes.Status400BadRequest;
        context.Response.Headers.CacheControl = "no-store";
        context.Response.ContentType = "text/plain; charset=utf-8";
        await context.Response.WriteAsync(parseError ?? "Invalid text SVG options.");
        return;
    }

    if (!TryGenerateTextSvg(options, out var svg, out var generationError))
    {
        context.Response.StatusCode = StatusCodes.Status400BadRequest;
        context.Response.Headers.CacheControl = "no-store";
        context.Response.ContentType = "text/plain; charset=utf-8";
        await context.Response.WriteAsync(generationError ?? "Invalid text SVG options.");
        return;
    }

    context.Response.Headers.CacheControl = "no-store";
    context.Response.ContentType = "image/svg+xml; charset=utf-8";
    await context.Response.WriteAsync(svg);
}));

